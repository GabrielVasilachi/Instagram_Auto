function VisualPreview({ draft, branding }: { draft: Draft; branding: Dashboard['branding'] }) {
  const [clock, setClock] = useState(0);
  let plan: ReturnType<typeof planReel> | null = null,
    error = '';
  try {
    if (draft.format === 'reel') plan = planReel(draft.quote, draft.design);
  } catch (reason) {
    error = reason instanceof Error ? reason.message : 'Simplifică textul.';
  }
  useEffect(() => {
    const start = performance.now();
    const timer = window.setInterval(() => setClock((performance.now() - start) / 1000), 33);
    return () => clearInterval(timer);
  }, [draft.quote, draft.format]);
  const t = plan ? clock % plan.duration : 0;
  const scene = plan?.scenes.find((s) => t >= s.start && t < s.end);
  const opacity = scene
    ? Math.max(0, Math.min(1, (t - scene.start) / 0.35, (scene.end - t) / 0.4))
    : 0;
  const fonts: Record<string, string> = {
    sans: 'Studio Sans',
    serif: 'Studio Serif',
    mono: 'Studio Mono',
  };
  const style = {
    textAlign: draft.design.textAlign as 'left' | 'center' | 'right',
    fontFamily: fonts[draft.design.font],
    fontSize: `${Math.max(17, draft.design.fontSize / 3)}px`,
    letterSpacing: `${draft.design.letterSpacing / 3}px`,
    lineHeight: draft.design.lineHeight / 100,
    textTransform:
      draft.design.textCase === 'uppercase' ? ('uppercase' as const) : ('none' as const),
    opacity: plan ? opacity : 1,
    transform: plan ? `translateY(${(1 - opacity) * 2.7}px)` : undefined,
  };
  return (
    <>
      <div
        className={`post-preview ${draft.format} theme-${draft.design.template} position-${draft.design.textPosition}`}
        style={{ '--overlay': draft.design.overlayOpacity / 100 } as React.CSSProperties}
      >
        <span className="preview-mark">{branding.name.toUpperCase()}</span>
        <div className="preview-message" style={style}>
          <p>{plan ? scene?.text || '' : draft.quote}</p>
          <span
            className={`accent-line align-${draft.design.textAlign}`}
            style={{ background: draft.accent }}
          />
        </div>
        <small>@{branding.username}</small>
      </div>
      {plan && (
        <p className="settings-note">
          {plan.mood} · {plan.scenes.length} scene · {plan.duration}s · Preview de timing. Randarea
          exactă și sunetul sunt disponibile din Content.
        </p>
      )}
      {error && <p role="alert">{error}</p>}
    </>
  );
}

