function App() {
  const [session, setSession] = useState<'loading' | 'authenticated' | 'anonymous'>('loading');
  useEffect(() => {
    fetch('/api/auth/session')
      .then((response) => response.json())
      .then((result) => setSession(result.authenticated ? 'authenticated' : 'anonymous'))
      .catch(() => setSession('anonymous'));
  }, []);
  if (session === 'loading')
    return (
      <main className="splash">
        <div className="brand">
          <span>SF</span>
          <strong>Silent Forward</strong>
        </div>
      </main>
    );
  if (session === 'anonymous') return <Login onAuthenticated={() => setSession('authenticated')} />;
  if (window.location.pathname.replace(/\/$/, '') === '/video-editor')
    return (
      <Suspense fallback={<main className="splash">Opening Video Editor…</main>}>
        <VideoEditor />
      </Suspense>
    );
  return <DashboardApp onLogout={() => setSession('anonymous')} />;
}

export default App;
