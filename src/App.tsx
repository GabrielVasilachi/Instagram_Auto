function ContentCalendar({
  posts,
  onPreview,
  onCreate,
}: {
  posts: Post[];
  onPreview: (id: string) => void;
  onCreate: () => void;
}) {
  const [month, setMonth] = useState(() => dateKey(new Date().toISOString()).slice(0, 7));
  const [view, setView] = useState('month');
  const [selectedDay, setSelectedDay] = useState('');
  const [year, number] = month.split('-').map(Number);
  const start = new Date(year, number - 1, 1),
    count = new Date(year, number, 0).getDate(),
    offset = (start.getDay() + 6) % 7;
  const monthly = posts
    .filter((p) => dateKey(p.scheduledFor).startsWith(month))
    .sort((a, b) => Date.parse(a.scheduledFor) - Date.parse(b.scheduledFor));
  const grouped = Object.entries(
    monthly.reduce<Record<string, Post[]>>((all, p) => {
      (all[dateKey(p.scheduledFor)] ||= []).push(p);
      return all;
    }, {}),
  );
  const changeMonth = (delta: number) => {
    const next = new Date(year, number - 1 + delta, 1);
    setMonth(`${next.getFullYear()}-${String(next.getMonth() + 1).padStart(2, '0')}`);
    setSelectedDay('');
  };
  return (
    <section className="calendar-section">
      <div className="calendar-toolbar">
        <div className="calendar-navigation">
          <button
            className="icon-button"
            aria-label="Luna precedentă"
            onClick={() => changeMonth(-1)}
          >
            <Icon name="back" />
          </button>
          <h2>{start.toLocaleDateString('ro-RO', { month: 'long', year: 'numeric' })}</h2>
          <button
            className="icon-button"
            aria-label="Luna următoare"
            onClick={() => changeMonth(1)}
          >
            <Icon name="chevron" />
          </button>
          <button
            className="secondary"
            onClick={() => {
              setMonth(dateKey(new Date().toISOString()).slice(0, 7));
              setSelectedDay('');
            }}
          >
            Astăzi
          </button>
        </div>
        <div className="view-toggle">
          <button
            className={view === 'month' ? 'active' : ''}
            aria-pressed={view === 'month'}
            onClick={() => setView('month')}
          >
            Lună
          </button>
          <button
            className={view === 'list' ? 'active' : ''}
            aria-pressed={view === 'list'}
            onClick={() => setView('list')}
          >
            Listă
          </button>
        </div>
      </div>
      {view === 'month' && (
        <div className="calendar-scroll">
          <div className="calendar-grid">
            {['Lun', 'Mar', 'Mie', 'Joi', 'Vin', 'Sâm', 'Dum'].map((d) => (
              <div className="calendar-weekday" key={d}>
                {d}
              </div>
            ))}
            {Array.from({ length: offset }, (_, i) => (
              <div key={`blank-${i}`} className="calendar-day outside" />
            ))}
            {Array.from({ length: count }, (_, i) => {
              const key = `${month}-${String(i + 1).padStart(2, '0')}`,
                dayPosts = monthly.filter((p) => dateKey(p.scheduledFor) === key);
              return (
                <div
                  key={key}
                  className={`calendar-day ${selectedDay === key ? 'selected' : ''} ${dateKey(new Date().toISOString()) === key ? 'today' : ''}`}
                >
                  <button
                    className="day-number"
                    onClick={() => setSelectedDay(selectedDay === key ? '' : key)}
                    aria-label={`Vezi ${key}`}
                  >
                    {i + 1}
                  </button>
                  {dayPosts.slice(0, 3).map((post) => (
                    <button
                      key={post.id}
                      className={`calendar-event ${post.status}`}
                      onClick={() => onPreview(post.id)}
                      title={post.quote}
                    >
                      <i />
                      <time>
                        {new Date(post.scheduledFor).toLocaleTimeString('ro-RO', {
                          hour: '2-digit',
                          minute: '2-digit',
                        })}
                      </time>
                      <span>{post.quote}</span>
                    </button>
                  ))}
                  {dayPosts.length > 3 && (
                    <button className="text-link more-events" onClick={() => setSelectedDay(key)}>
                      +{dayPosts.length - 3} elemente
                    </button>
                  )}
                </div>
              );
            })}
          </div>
        </div>
      )}
      <div className="calendar-list">
        {selectedDay && (
          <div className="results-summary">
            <strong>{selectedDay}</strong>
            <button className="text-link" onClick={() => setSelectedDay('')}>
              Toată luna
            </button>
          </div>
        )}
        {(view === 'list' || selectedDay) &&
          grouped
            .filter(([key]) => !selectedDay || key === selectedDay)
            .map(([key, dayPosts]) => (
              <section key={key} className="calendar-agenda">
                <h3>{shortDay(dayPosts[0].scheduledFor)}</h3>
                {dayPosts.map((post) => (
                  <button className="agenda-item" key={post.id} onClick={() => onPreview(post.id)}>
                    <time>
                      {new Date(post.scheduledFor).toLocaleTimeString('ro-RO', {
                        hour: '2-digit',
                        minute: '2-digit',
                      })}
                    </time>
                    <Icon name={post.format === 'reel' ? 'video' : 'image'} />
                    <strong>{post.quote}</strong>
                    <StatusBadge status={post.status} />
                  </button>
                ))}
              </section>
            ))}
      </div>
      {!monthly.length && (
        <EmptyState
          title="O lună plină de posibilități"
          description="Nu există conținut în această lună."
          action={
            <button className="primary" onClick={onCreate}>
              Creează conținut
            </button>
          }
        />
      )}
      {selectedDay && !grouped.some(([key]) => key === selectedDay) && (
        <p className="empty">Nu există conținut pentru această zi.</p>
      )}
    </section>
  );
}

