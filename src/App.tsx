function Analytics({
  posts,
  recentDays,
}: {
  posts: Post[];
  recentDays: { key: string; label: string; count: number }[];
}) {
  const published = posts.filter((post) => post.status === 'published'),
    measured = published.filter((post) => post.design.performance),
    totalViews = measured.reduce((sum, post) => sum + (post.design.performance?.views || 0), 0),
    totalShares = measured.reduce((sum, post) => sum + (post.design.performance?.shares || 0), 0),
    totalSaves = measured.reduce((sum, post) => sum + (post.design.performance?.saved || 0), 0),
    measuredReels = measured.filter((post) => post.format === 'reel'),
    averageWatch =
      measuredReels.reduce(
        (sum, post) => sum + (post.design.performance?.averageWatchTimeMs || 0),
        0,
      ) /
      Math.max(1, measuredReels.length) /
      1000;
  const recipeGroups = measured.reduce<Record<string, { total: number; count: number }>>(
    (result, post) => {
      const recipe = post.design.growth?.recipe || post.design.template;
      const group = (result[recipe] ||= { total: 0, count: 0 });
      group.total += post.design.performance?.score || 0;
      group.count += 1;
      return result;
    },
    {},
  );
  const recipes = Object.entries(recipeGroups)
    .map(([recipe, value]) => [recipe, Math.round(value.total / value.count)] as const)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 6);
  return (
    <>
      <section className="analytics-cards">
        <Metric
          label="Views măsurate"
          value={totalViews}
          detail={`${measured.length} materiale analizate`}
          trend="Insights"
        />
        <Metric label="Distribuiri" value={totalShares} detail="semnal de reach" trend="Priority" />
        <Metric
          label="Salvări"
          value={totalSaves}
          detail="valoare pe termen lung"
          trend="Quality"
        />
        <Metric
          label="Watch mediu"
          value={`${averageWatch.toFixed(1)}s`}
          detail="Reel-uri analizate"
          trend="Retention"
        />
      </section>
      <section className="analytics-grid">
        <div className="panel">
          <SectionHead eyebrow="OUTPUT" title="Ultimele 7 zile" />
          <div className="large-chart">
            {recentDays.map((day) => (
              <div key={day.key}>
                <span>
                  <i style={{ height: `${Math.max(4, day.count * 28)}px` }} />
                </span>
                <strong>{day.count}</strong>
                <small>{day.label}</small>
              </div>
            ))}
          </div>
          <div className="growth-signals">
            <span>
              <strong>Watch time</strong>
              <small>Hook în prima secundă</small>
            </span>
            <span>
              <strong>Shares</strong>
              <small>Mesaje trimise în DM</small>
            </span>
            <span>
              <strong>Saves</strong>
              <small>Idei de revăzut</small>
            </span>
          </div>
        </div>
        <div className="panel">
          <SectionHead eyebrow="GROWTH LAB" title="Rețete după performanță" />
          <div className="ranking">
            {recipes.map(([recipe, score], index) => (
              <div key={recipe}>
                <span>{index + 1}</span>
                <strong>{recipe}</strong>
                <i>
                  <b style={{ width: `${score}%` }} />
                </i>
                <em>{score}</em>
              </div>
            ))}
            {!recipes.length && (
              <p className="empty">Insights se colectează automat după publicare.</p>
            )}
          </div>
          <p className="settings-note">
            Motorul folosește 75% rețete validate și 25% experimente noi. Scorul combină retenția,
            distribuirile, salvările, aprecierile și comentariile.
          </p>
        </div>
      </section>
    </>
  );
}
